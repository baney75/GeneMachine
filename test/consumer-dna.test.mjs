test("rejects VCF, multiple-sample tables, and input over the configured safety limit", () => {
  assert.throws(
    () => parseConsumerDna(`##fileformat=VCFv4.2\n#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE\n12\t21331549\trs4149056\tT\tC\t.\tPASS\t.\tGT\t0/1`, "sample.vcf"),
    /VCF input is not supported/,
  );
  assert.throws(
    () => parseConsumerDna(`rsid\tchromosome\tposition\tgenotype\tsample_id\nrs1\t1\t100\tAA\tperson-1`, "multi.tsv"),
    /Multiple-sample or repeated genotype columns/,
  );
  assert.throws(
    () => parseConsumerDna("x".repeat(51), "large.txt", { maxCharacters: 50 }),
    /too large to inspect safely/,
  );
  assert.throws(
    () => parseConsumerDna(`rsid\tchromosome\tposition\tgenotype\nrs1\t1\t100\tAA\nrs2\t1\t101\tCC`, "too-many-rows.tsv", { maxVariantRows: 1 }),
    /1-variant in-memory safety limit/,
  );
});
