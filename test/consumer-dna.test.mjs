const supportedHeader = `# Synthetic reference fixture; no real person\n# build 37\n# forward strand\nrsid\tchromosome\tposition\tgenotype`;

test("retains normalized marker facts without retaining raw rows", () => {
  const report = parseConsumerDna(`${supportedHeader}\nRS4149056\t12\t21331549\tTC`, "synthetic-reference.tsv");
  assert.deepEqual(findMarkerObservations(report, "rs4149056"), [{
    rsid: "rs4149056",
    chromosome: "12",
    position: 21331549,
    genotype: "TC",
    noCall: false,
  }]);
  assert.equal(Object.isFrozen(report.markers), true);
  assert.equal("raw" in report.markers[0], false);
});

test("supports only a pinned exact-marker observation and separates its limits", () => {
  const fixtureUrl = new URL("../samples/reference/slco1b1-rs4149056-grch37-forward.tsv", import.meta.url);
  const report = parseConsumerDna(readFileSync(fixtureUrl, "utf8"), "slco1b1-rs4149056-grch37-forward.tsv");
  const result = evaluateSlco1b1ExactMarker(report);
  assert.equal(result.status, "supported_observation");
  assert.equal(result.observedGenotype.genotype, "TC");
  assert.equal(result.validation.status, "input_consistency_checks_passed");
  assert.equal(result.phenotypeMapping.status, "not_performed");
  assert.equal(result.guidelineEvidence.status, "context_only");
  assert.match(result.validation.detail, /not analytical or clinical validation/i);
  assert.match(result.clinicianDiscussion, /before changing treatment/i);

  const capability = createPharmacogeneticCapabilityMap(report);
  assert.equal(capability.exactMarker.status, "supported_observation");
  assert.equal(capability.starAlleles.status, "unavailable");
  assert.equal(capability.complexGenes.status, "unavailable");
});

test("treats a missing locus as unknown and names an appropriate additional test", () => {
  const report = parseConsumerDna(`${supportedHeader}\nrs1\t1\t100\tAA`, "missing.tsv");
  const result = evaluateSlco1b1ExactMarker(report);
  assert.equal(result.status, "abstain");
  assert.equal(result.reasonCode, "marker_missing");
  assert.match(result.validation.detail, /unknown, not a reference or normal call/i);
  assert.match(result.additionalTest, /clinically validated pharmacogenetic test/i);
});

test("abstains when build or strand orientation is ambiguous", () => {
  const noBuild = parseConsumerDna(`# forward strand\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, "no-build.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(noBuild).reasonCode, "unsupported_or_missing_build");

  const noStrand = parseConsumerDna(`# build 37\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, "no-strand.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(noStrand).reasonCode, "missing_or_unsupported_orientation");

  const reverse = parseConsumerDna(`# build 37\n# reverse strand\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tAG`, "reverse.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(reverse).reasonCode, "missing_or_unsupported_orientation");

  const parentheticalReverse = parseConsumerDna(`# build 37\n# genotype is reported on the reverse (-) strand\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tAG`, "reverse-parenthetical.tsv");
  assert.equal(parentheticalReverse.orientation.value, "reverse");
  assert.equal(evaluateSlco1b1ExactMarker(parentheticalReverse).reasonCode, "missing_or_unsupported_orientation");

  const conflicting = parseConsumerDna(`# build 37\n# forward (+) strand; reverse (-) strand\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, "conflicting-strand.tsv");
  assert.equal(conflicting.orientation.value, null);
  assert.equal(conflicting.orientation.label, "Conflicting strand declarations");
  assert.equal(evaluateSlco1b1ExactMarker(conflicting).reasonCode, "missing_or_unsupported_orientation");
});

test("does not turn negated, prefixed, or compound direction language into a forward declaration", () => {
  for (const declaration of [
    "not forward strand",
    "no forward strand",
    "without a plus strand declaration",
    "non-forward strand",
    "unforward strand",
    "not plus strand",
    "possibly forward strand",
    "reverse-forward strand",
    "reverse / forward strand",
    "minus or plus orientation",
  ]) {
    const report = parseConsumerDna(`# build 37\n# ${declaration}\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, `${declaration}.tsv`);
    assert.equal(report.orientation.value, null, declaration);
    assert.equal(evaluateSlco1b1ExactMarker(report).reasonCode, "missing_or_unsupported_orientation", declaration);
  }
});

test("treats invalid orientation evidence anywhere in a multi-line header as a global abstention", () => {
  for (const comments of [
    ["orientation is unknown", "forward strand"],
    ["no forward strand", "orientation: +"],
    ["forward strand", "orientation is unknown"],
    ["- / + strand"],
    ["maybe + strand"],
    ["forward strand; unknown"],
    ["forward strand. unknown"],
    ["forward strand; not confirmed"],
    ["not; forward strand"],
    [`not ${"filler ".repeat(16)}forward strand`],
    ["perhaps forward strand"],
    ["unknown", "forward strand"],
    ["forward strand?"],
    ["unverified forward strand"],
    ["forward strand remains unverified"],
    ["tentative forward strand"],
    ["provisional forward strand"],
    ["likely forward strand"],
    ["probably forward strand"],
    ["+ strand; provisional"],
  ]) {
    const report = parseConsumerDna(`# build 37\n${comments.map((comment) => `# ${comment}`).join("\n")}\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, "ambiguous-orientation.tsv");
    assert.equal(report.orientation.value, null, comments.join(" / "));
    assert.equal(report.orientation.evidence, "File header conflict", comments.join(" / "));
    assert.equal(evaluateSlco1b1ExactMarker(report).reasonCode, "missing_or_unsupported_orientation", comments.join(" / "));
  }
});

test("does not hide late or post-column strand contradictions", () => {
  const lateContradiction = parseConsumerDna(`# build 37\n# forward strand\n# ${"x".repeat(510)} reverse strand\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, "late-contradiction.tsv");
  assert.equal(lateContradiction.orientation.value, null);
  assert.equal(evaluateSlco1b1ExactMarker(lateContradiction).reasonCode, "missing_or_unsupported_orientation");

  const postColumnContradiction = parseConsumerDna(`# build 37\n# forward strand\nrsid\tchromosome\tposition\tgenotype\n# reverse strand\nrs4149056\t12\t21331549\tTC`, "post-column-contradiction.tsv");
  assert.equal(postColumnContradiction.orientation.value, null);
  assert.equal(evaluateSlco1b1ExactMarker(postColumnContradiction).reasonCode, "missing_or_unsupported_orientation");

  assert.throws(
    () => parseConsumerDna(`# ${"x".repeat(16_385)} forward strand\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, "oversized-header.tsv"),
    /header is too large to verify build and strand orientation safely/i,
  );
});

test("rejects invisible or non-ASCII Unicode before it can hide orientation evidence", () => {
  const zeroWidthPrefix = `# build 37\n# forward strand\nrsid\tchromosome\tposition\tgenotype\n\u200B# reverse strand\nrs4149056\t12\t21331549\tTC`;
  const zeroWidthWords = `# build 37\n# forward strand\nrsid\tchromosome\tposition\tgenotype\n# rev\u200Berse str\u200Band\nrs4149056\t12\t21331549\tTC`;
  assert.throws(() => parseConsumerDna(zeroWidthPrefix, "zero-width-prefix.tsv"), /non-ASCII or invisible Unicode formatting/);
  assert.throws(() => parseConsumerDna(zeroWidthWords, "zero-width-words.tsv"), /non-ASCII or invisible Unicode formatting/);

  const leadingBom = parseConsumerDna(`\uFEFF${supportedHeader}\nrs4149056\t12\t21331549\tTC`, "leading-bom.tsv");
  assert.equal(leadingBom.orientation.value, "forward");
  assert.equal(evaluateSlco1b1ExactMarker(leadingBom).status, "supported_observation");
});

test("recognizes bounded symbolic declarations without inferring an unidentified orientation", () => {
  for (const declaration of ["+ strand", "orientation: +", "(+) strand"]) {
    const report = parseConsumerDna(`# build 37\n# ${declaration}\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, `${declaration}.tsv`);
    assert.equal(report.orientation.value, "forward", declaration);
    assert.equal(evaluateSlco1b1ExactMarker(report).status, "supported_observation", declaration);
  }
  for (const declaration of ["- strand", "orientation: -", "(-) strand"]) {
    const report = parseConsumerDna(`# build 37\n# ${declaration}\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tAG`, `${declaration}.tsv`);
    assert.equal(report.orientation.value, "reverse", declaration);
    assert.equal(evaluateSlco1b1ExactMarker(report).reasonCode, "missing_or_unsupported_orientation", declaration);
  }
  const unidentified = parseConsumerDna(`# build 37\n# orientation is unknown\nrsid\tchromosome\tposition\tgenotype\nrs4149056\t12\t21331549\tTC`, "unknown-orientation.tsv");
  assert.equal(unidentified.orientation.value, null);
  assert.equal(evaluateSlco1b1ExactMarker(unidentified).reasonCode, "missing_or_unsupported_orientation");
});

test("abstains for duplicate, conflicting, no-call, and coordinate-mismatched target rows", () => {
  const duplicate = parseConsumerDna(`${supportedHeader}\nrs4149056\t12\t21331549\tTC\nrs4149056\t12\t21331549\tCT`, "duplicate.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(duplicate).reasonCode, "duplicate_marker");

  const conflict = parseConsumerDna(`${supportedHeader}\nrs4149056\t12\t21331549\tTT\nrs4149056\t12\t21331549\tTC`, "conflict.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(conflict).reasonCode, "conflicting_duplicate");

  const noCall = parseConsumerDna(`${supportedHeader}\nrs4149056\t12\t21331549\t--`, "no-call.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(noCall).reasonCode, "no_call");

  const wrongCoordinate = parseConsumerDna(`${supportedHeader}\nrs4149056\t12\t1\tTC`, "wrong-coordinate.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(wrongCoordinate).reasonCode, "coordinate_mismatch");

  const unexpectedAllele = parseConsumerDna(`${supportedHeader}\nrs4149056\t12\t21331549\tAG`, "unexpected-allele.tsv");
  assert.equal(evaluateSlco1b1ExactMarker(unexpectedAllele).reasonCode, "unexpected_allele");
});

